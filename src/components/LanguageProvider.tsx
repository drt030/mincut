export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("capability_graph_language");
    if (saved === "zh" || saved === "en") setLanguageState(saved);
  }, []);

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem("capability_graph_language", next);
  };

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key) => uiText[language][key] ?? uiText.en[key] ?? key,
      nodeName: (id, fallback) => (language === "zh" ? nodeTextZh[id] ?? fallback : fallback),
      kindName: (kind) => (language === "zh" ? kindTextZh[kind] ?? kind : kind),
      relationName: (relation) => (language === "zh" ? relationTextZh[relation] ?? relation : relation),
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
